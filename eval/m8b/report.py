#!/usr/bin/env python3
"""Milestone 8b (M8_PLAN.md §4.3): generate eval/m8b/DIAG.md from the data files alone. Facts only:
reading them is for the design note.

  python3 eval/m8b/report.py

Inputs (eval/m8b/): specs_points.jsonl, points/results.jsonl, points/sections.jsonl, points/timing.json,
specs_models.jsonl, models/m8a.jsonl, models/named.jsonl, specs_named.jsonl.
Shares are given two ways: *pooled* (clauses summed over the points, over the summed total) and as the
*median* of the per-point shares. Only the standard library is used; output is sorted throughout.
"""
import collections, json, os, statistics

D = os.path.dirname(os.path.abspath(__file__))
VARIANTS = [("rules", "with the 8a rules"), ("norules", "milestone 7's H, no rules")]
GROUPS = [("rewrite_B", "rewriting, Tier B"), ("rewrite_A", "rewriting, Tier A"), ("control", "control")]


def load(p):
    out = []
    if os.path.exists(p):
        for l in open(p):
            l = l.strip()
            if l:
                try:
                    out.append(json.loads(l))
                except json.JSONDecodeError:
                    pass
    return out


def fmt(x):
    if isinstance(x, float):
        return f"{int(x):,}" if x.is_integer() else f"{x:,.1f}"
    return f"{x:,}" if isinstance(x, int) else str(x)


def table(head, rows):
    return (["| " + " | ".join(head) + " |", "| " + " | ".join("---" for _ in head) + " |"]
            + ["| " + " | ".join(fmt(x) for x in r) + " |" for r in rows])


def pct(a, b):
    return f"{100 * a / b:.1f}%" if b else "–"


def med(xs):
    return statistics.median(xs) if xs else None


def mpct(xs):
    m = med(xs)
    return f"{100 * m:.1f}%" if m is not None else "–"


def main():
    specs = {s["key"]: s for s in load(os.path.join(D, "specs_points.jsonl"))}
    res = {r["key"]: r for r in load(os.path.join(D, "points", "results.jsonl"))}
    sec = collections.defaultdict(dict)
    for r in load(os.path.join(D, "points", "sections.jsonl")):
        if "section" in r:
            sec[r["key"]][r["section"]] = r["data"]
    tp = os.path.join(D, "points", "timing.json")
    tm = json.load(open(tp)) if os.path.exists(tp) else {}
    var = lambda k: specs[k]["m8b_variant"]
    grp = lambda k: specs[k]["probe_group"]
    keys = sorted(k for k in specs if k in res)
    full = [k for k in keys if res[k]["status"] == "ok"]
    out = ["# 8b: measurements of the CNF's structure (M8_PLAN §4.3)", "",
           "Generated by `eval/m8b/report.py` from the data files alone. Facts only; reading them is for the design note.", "",
           f"Points: the 200 goals of 8a at N = {tm.get('N', 5)}, each with the 8a rules (amendment 4.1) and with milestone 7's H "
           f"(no rules), {len(specs)} in all; {len(keys)} measured, {len(full)} with every section. Every point is a `countOnly` "
           "encode, recounted family by family (`Test/M8Diag.lean`). *Pooled*: clauses summed over the points, over the summed "
           "total. *Median*: the median over points of the per-point share.", ""]
    st = collections.Counter((var(k), res[k]["status"]) for k in keys)
    out += table(["variant", "points", "ok", "memout", "crash"],
                 [[n, sum(1 for k in keys if var(k) == v), st.get((v, "ok"), 0), st.get((v, "memout"), 0), st.get((v, "crash"), 0)]
                  for v, n in VARIANTS]) + [""]
    bad = [k for k in keys for s in ("m2", "m3") if s in sec[k] and sec[k][s].get("check_total_equal") is False]
    km = [k for k in keys if "m2" in sec[k] and sec[k]["m2"].get("check_kept_mismatch")]
    out += [f"**Recount checks.** The recounted groundness and decomposition totals equal the encoder's family counts on "
            f"{sum(1 for k in keys for s in ('m2', 'm3') if s in sec[k] and sec[k][s].get('check_total_equal'))} of "
            f"{sum(1 for k in keys for s in ('m2', 'm3') if s in sec[k])} sections (failures: {len(bad)}); kept candidates differ "
            f"from the encoder's on {len(km)} points.", ""]
    mo = [k for k in keys if res[k]["status"] != "ok"]
    if mo:
        out += ["Points that did not finish (the last section completed):", ""]
        out += table(["point", "status", "last section", "clauses at N = 5"],
                     [[f"`{k[4:]}`", res[k]["status"], res[k].get("last_section") or "–",
                       sec[k].get("encode", {}).get("clauses", "–")] for k in mo]) + [""]

    # M1
    rows = []
    for v, n in VARIANTS:
        ks = [k for k in keys if var(k) == v and "m1" in sec[k]]
        for f in ("sym", "idx", "rank", "esc", "open", "W"):
            xs = sorted(sec[k]["m1"][f] for k in ks)
            rows.append([n, f, len(xs), xs[0], fmt(med(xs)), xs[-1]])
    out += ["## M1 Label width", "", "Bits per label field (SPEC 5.3) and the total width W.", ""]
    out += table(["variant", "field", "points", "min", "median", "max"], rows) + [""]

    # M2
    def shares(section, prefix, ks):
        tot = sum(sec[k]["encode"]["clauses"] for k in ks)
        fam = sum(sec[k][section]["total"] for k in ks)
        cats = sorted({c for k in ks for c in sec[k][section]["by"] if c.startswith(prefix) and "|" not in c})
        rows = []
        for c in cats:
            a = sum(sec[k][section]["by"].get(c, {}).get("clauses", 0) for k in ks)
            ps = [sec[k][section]["by"].get(c, {}).get("clauses", 0) / sec[k]["encode"]["clauses"] for k in ks]
            pf = [sec[k][section]["by"].get(c, {}).get("clauses", 0) / sec[k][section]["total"] for k in ks if sec[k][section]["total"]]
            rows.append([c.split(":", 1)[1] if ":" in c else c, a, pct(a, tot), mpct(ps), pct(a, fam), mpct(pf)])
        return rows, tot, fam
    out += ["## M2 Groundness by candidate", "",
            "Groundness clauses (SPEC 6.8) by the kind of the candidate, and by the candidate's node index against the slot's "
            "(a ground object has no node). *at-least-one per slot*: the clause `cl ⇒ some sv`. Shares of all clauses and of "
            "the groundness family.", ""]
    for v, n in VARIANTS:
        ks = [k for k in keys if var(k) == v and "m2" in sec[k] and "encode" in sec[k]]
        for prefix, what in (("kind:", "by kind"), ("node:", "by node")):
            rows, tot, fam = shares("m2", prefix, ks)
            if prefix == "kind:":
                a = sum(sec[k]["m2"]["by"].get("at-least-one per slot", {}).get("clauses", 0) for k in ks)
                rows.append(["at-least-one per slot", a, pct(a, tot),
                             mpct([sec[k]["m2"]["by"].get("at-least-one per slot", {}).get("clauses", 0) / sec[k]["encode"]["clauses"] for k in ks]),
                             pct(a, fam), mpct([sec[k]["m2"]["by"].get("at-least-one per slot", {}).get("clauses", 0) / sec[k]["m2"]["total"]
                                                for k in ks if sec[k]["m2"]["total"]])])
            out += [f"**{n}, {what}** ({len(ks)} points; groundness is {pct(fam, tot)} of all clauses, pooled):", ""]
            out += table(["class", "clauses", "of all, pooled", "of all, median", "of groundness, pooled", "of groundness, median"], rows) + [""]
        sv = collections.Counter()
        for k in ks:
            for c, x in sec[k]["m2"]["by"].items():
                if c.startswith("kind:") and "|" not in c:
                    sv[c[5:]] += x["vars"]
        out += [f"`sv` variables by kind ({n}): " + ", ".join(f"{c} {fmt(x)}" for c, x in sorted(sv.items()))
                + f". Candidates dropped by the static typing decision: {fmt(sum(sec[k]['m2']['dropped_static_typing'] for k in ks))}"
                f"; by candidate pruning: {fmt(sum(sec[k]['m2']['dropped_candidate_pruning'] for k in ks))}; considered: "
                f"{fmt(sum(sec[k]['m2']['candidates_considered'] for k in ks))}.", ""]
        cross = collections.Counter()
        for k in ks:
            for c, x in sec[k]["m2"]["by"].items():
                if c.count("|") == 1:
                    cross[tuple(p.split(":", 1)[1] for p in c.split("|"))] += x["clauses"]
        kinds = sorted({a for a, _ in cross})
        rels = sorted({b for _, b in cross})
        tot = sum(sec[k]["m2"]["total"] for k in ks)
        out += [f"Kind (rows) by node (columns), share of groundness, pooled ({n}):", ""]
        out += table(["kind"] + rels, [[a] + [pct(cross[(a, b)], tot) for b in rels] for a in kinds]) + [""]

    # M3
    out += ["## M3 Decomposition by pair", "",
            "Decomposition clauses (SPEC 6.5) by whether the two objects belong to the same node, to different nodes, or one is "
            "ground; by whether their templates lie in the same static may-equal component; and by branch (a full pair, or pair "
            "pruning's idx-differs clause). Shares of all clauses and of the decomposition family.", "",
            "*May-equal component* (the rule, `Test/M8Diag.lean` `components`): template positions with all node copies "
            "identified (a variable is one key across all frames, so links join nothing further), joined by matching (each argument "
            "of a target with the same argument of every head it can match, and a data position's variable with the clause's "
            "value), by groundness (each clause variable with every candidate the encoder keeps for it), by typing clauses (the "
            "two type templates), and closed under decomposition (two keys with the same symbol and arity in one component join "
            "their children).", ""]
    for v, n in VARIANTS:
        ks = [k for k in keys if var(k) == v and "m3" in sec[k] and "encode" in sec[k]]
        for prefix, what in (("node:", "by node"), ("component:", "by component"), ("branch:", "by branch")):
            rows, tot, fam = shares("m3", prefix, ks)
            out += [f"**{n}, {what}** ({len(ks)} points; decomposition is {pct(fam, tot)} of all clauses, pooled):", ""]
            out += table(["class", "clauses", "of all, pooled", "of all, median", "of decomposition, pooled",
                          "of decomposition, median"], rows) + [""]
        sym = collections.Counter()
        for k in ks:
            for s, x in sec[k]["m3"]["top_symbols"]:
                sym[s] += x
        fam = sum(sec[k]["m3"]["total"] for k in ks)
        out += [f"Symbols with the most decomposition clauses, summed over each point's 10 largest ({n}):", ""]
        out += table(["symbol / arity", "clauses", "of decomposition, pooled"],
                     [[f"`{s}`", x, pct(x, fam)] for s, x in sorted(sym.items(), key=lambda z: (-z[1], z[0]))[:10]]) + [""]
        top1 = [sec[k]["m3"]["top_symbols"][0][1] / sec[k]["m3"]["total"] for k in ks if sec[k]["m3"]["top_symbols"] and sec[k]["m3"]["total"]]
        top10 = [sum(x for _, x in sec[k]["m3"]["top_symbols"]) / sec[k]["m3"]["total"] for k in ks if sec[k]["m3"]["total"]]
        out += [f"Per point ({n}): the largest symbol's share of decomposition, median {mpct(top1)}; the 10 largest, median "
                f"{mpct(top10)}; distinct symbols with pairs, median {fmt(med([sec[k]['m3']['symbols'] for k in ks]))}.", ""]

    # M4
    out += ["## M4 Node–clause bounds", "",
            "d(g): least depth, s(g): least proof size, of each goal or data position, by a fixpoint that ignores unification; a "
            "clause's minimal size is 1 plus its premises' least sizes. `gp(α, g)` is possible only if d(g) ≤ α and α + s(g) ≤ N; "
            "`cl(α, c)` only if some position c can match passes the same test with c's minimal size. *Dead*: groundness clauses "
            "of an excluded `cl(α, c)`, and decomposition clauses of a pair with an excluded activation literal; they are satisfied "
            "in every model. The argument is checked in NOTES.md (\"8b: measurements\").", ""]
    rows = []
    for v, n in VARIANTS:
        for g, gn in GROUPS + [("all", "all")]:
            ks = [k for k in keys if var(k) == v and (g == "all" or grp(k) == g) and "m4" in sec[k]]
            if not ks:
                continue
            m = lambda f: sum(sec[k]["m4"][f] for k in ks)
            share = lambda a, b: [sec[k]["m4"][a] / sec[k]["m4"][b] for k in ks if sec[k]["m4"][b]]
            rows.append([n, gn, len(ks), pct(m("gp_excluded"), m("gp_pairs")), pct(m("cl_excluded"), m("cl_pairs")),
                         pct(m("groundness_dead"), m("groundness_clauses")), mpct(share("groundness_dead", "groundness_clauses")),
                         pct(m("decomposition_dead"), m("decomposition_clauses")), mpct(share("decomposition_dead", "decomposition_clauses")),
                         pct(m("groundness_dead") + m("decomposition_dead"), m("total_clauses"))])
    out += table(["variant", "group", "points", "gp excluded", "cl excluded", "groundness dead, pooled", "median",
                  "decomposition dead, pooled", "median", "dead of all clauses, pooled"], rows) + [""]

    # M5
    mspec = {s["key"]: s for s in load(os.path.join(D, "specs_models.jsonl"))}
    for name, path, what in (("m8a", "models/m8a.jsonl", "the 64 proved runs of 8a, with the rules"),
                             ("named", "models/named.jsonl", "the named cases with a proof (milestone 7's H)")):
        R = sorted(load(os.path.join(D, path)), key=lambda r: r["key"])
        if not R:
            continue
        rs = collections.Counter(r["result"] for r in R)
        ok = sum(1 for r in R if r.get("proof") == "ok")
        sameN = sum(1 for r in R if r.get("nodes") == r["N"])
        viol = sum(len(r.get("bound_violations", [])) for r in R)
        out += [f"## M5 Models: {what}", "",
                f"{len(R)} re-solves at the N where each was proved (solver limit 20 s): "
                + ", ".join(f"{k} {v}" for k, v in sorted(rs.items())) + f". Decoded proofs that pass the kernel check: {ok}. "
                f"Models whose proof has exactly N nodes: {sameN}. `gp` and `cl` pairs used: "
                f"{sum(r.get('pairs_used', 0) for r in R)}; M4 bound violations: **{viol}**.", ""]
        c = collections.Counter()
        for r in R:
            for k, x in r.get("slots", {}).items():
                c[k] += x["clauses"]
        nslots = sum(x for k, x in c.items() if k.startswith("kind:") and "|" not in k)
        kinds = sorted({k.split("|")[0][5:] for k in c if k.startswith("kind:")})
        rels = sorted({k.split("|")[1][5:] for k in c if "|" in k})
        out += [f"Grounded slots: {nslots}. The chosen candidate's kind (rows) and its node's relation to the slot's node in "
                "the decoded tree (columns):", ""]
        out += table(["kind"] + rels + ["all"], [[kd] + [c.get(f"kind:{kd}|node:{rl}", 0) for rl in rels] + [c.get(f"kind:{kd}", 0)]
                                                  for kd in kinds]
                     + [["all"] + [c.get(f"node:{rl}", 0) for rl in rels] + [nslots]]) + [""]
        if name == "m8a":
            byg = collections.Counter()
            for r in R:
                g = mspec[r["key"]]["probe_group"]
                for k, x in r.get("slots", {}).items():
                    if k.startswith("node:"):
                        byg[(g, k[5:])] += x["clauses"]
            out += ["By group (grounded slots by relation):", ""]
            out += table(["group"] + rels, [[gn] + [byg.get((g, rl), 0) for rl in rels] for g, gn in GROUPS]) + [""]
    open(os.path.join(D, "DIAG.md"), "w").write("\n".join(out) + "\n")
    print("wrote eval/m8b/DIAG.md")


