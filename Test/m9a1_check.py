#!/usr/bin/env python3
"""9a-1 (M9_PLAN 2.2): the 8a checks, recomputed from the data files.

  python3 Test/m9a1_check.py M8DATA_WORKTREE

reads eval/m9a1/count.jsonl (`eval_run iffeq-count eval/m9a1/specs_count.jsonl eval/m9a1/count.jsonl`),
eval/m9a1/runs8/results.jsonl (`SOLVE_BY_SAT_EVAL_FLAGS=nodeBounds,exclusivePairs,iffEq
python3 Test/eval_driver.py run eval/m9a1/specs_8.jsonl eval/m9a1/runs8`) and 8a's
eval/m8a/rules.jsonl on m8-data, and writes eval/m9a1/CHECKS.md. Exit 0 if both checks pass, 9 if not
(a stop: M9_PLAN 2.2).
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "Test"))
from m9a1_setup import EIGHT  # noqa: E402

D = os.path.join(ROOT, "eval", "m9a1")


def load(p):
    return [json.loads(l) for l in open(p) if l.strip()]


def main():
    w = sys.argv[1]
    rules = {r["key"]: r for r in load(os.path.join(w, "eval/m8a/rules.jsonl"))}
    count = load(os.path.join(D, "count.jsonl"))
    res = {r["key"]: r for r in load(os.path.join(D, "runs8", "results.jsonl"))}
    ok = True
    L = ["# 9a-1: the 8a checks (M9_PLAN 2.2)", "",
         "Generated by `python3 Test/m9a1_check.py` from `eval/m9a1/count.jsonl`, `eval/m9a1/runs8/` and 8a's "
         "`eval/m8a/rules.jsonl` (on tag m8-data). Milestone 7's H, `iffEq` on; the runs with node bounds and "
         "exclusive pairs on and milestone 7's limits.", "", "## The count", ""]
    bad = [(c["key"], c["iffeq_global"], rules["m8a:" + c["key"]]["probe_propext"]) for c in count
           if c["iffeq_global"] != 2 * rules["m8a:" + c["key"]]["probe_propext"]]
    g = sum(c["iffeq_global"] for c in count)
    p = sum(rules["m8a:" + c["key"]]["probe_propext"] for c in count)
    loc = sum(c["iffeq_local"] for c in count)
    ok &= not bad and len(count) == 200
    L += [f"- Specs: {len(count)}.",
          f"- `propext` paths from constants of H: **{g}**; twice 8a's `probe_propext` ({p}): {2 * p}. "
          f"Specs where they differ: {len(bad)}.",
          f"- Specs with such a path: {sum(1 for c in count if c['iffeq_global'])}; constants of H with one: "
          f"{sum(len(c['iffeq_per_constant']) for c in count)}.",
          f"- Paths from local hypotheses (counted separately): **{loc}**, in "
          f"{sum(1 for c in count if c['iffeq_local'])} spec(s): "
          + (", ".join(f"`{c['key']}` ({c['iffeq_local']})" for c in count if c["iffeq_local"]) or "none") + ".",
          f"- Paths dropped (notes): {sum(len(c['dropped']) for c in count)}. Specs whose accepted H changes with "
          f"`iffEq`: {sum(1 for c in count if not c['acceptance_unchanged'])}.", ""]
    for k, a, b in bad:
        L.append(f"- DIFFERS: `{k}`: {a} paths, 8a's probe_propext {b}")
    L += ["## The 8 proofs", "", "| goal | N in 8a | N expected | outcome | N | proof |", "| --- | --- | --- | --- | --- | --- |"]
    for gid, n8a, nexp in EIGHT:
        r = res.get("main:" + gid, {})
        good = r.get("outcome") == "proved" and r.get("N") == nexp
        ok &= good
        L.append(f"| `{gid}` | {n8a} | {nexp} | {r.get('outcome', 'missing')} | {r.get('N', '–')} | "
                 f"`{r.get('skeleton', '').split(' => ', 1)[-1]}` |")
    L += ["", f"Every proof is decoded and kernel-checked by the harness. Flags: "
          f"{sorted(set(tuple(r.get('enc_flags', [])) for r in res.values()))}.", "",
          f"**Result: {'both checks pass' if ok else 'A CHECK FAILS (stop)'}.**"]
    open(os.path.join(D, "CHECKS.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))
    return 0 if ok else 9


if __name__ == "__main__":
    sys.exit(main())
