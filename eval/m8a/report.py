#!/usr/bin/env python3
"""Milestone 8a (M8_PLAN.md §2.7, amendment 4.1 decision 6): generate eval/m8a/PROBE.md from the data
files alone. Facts only: reading them is for 8b.

  python3 eval/m8a/report.py [RUNDIR]      (default eval/m8a/full; writes RUNDIR/../PROBE.md for full)

Inputs (all under eval/m8a/): goals.jsonl, specs.jsonl, rules.jsonl, inputs/final.jsonl (milestone 7's
final results), inputs/population.jsonl (E5 obstacles), inputs/scaling_k0.jsonl (milestone 7's k = 0
sizes of the controls), RUNDIR/results.jsonl, RUNDIR/sizes.jsonl, RUNDIR/header.json.
Only the standard library is used. Output is sorted throughout, so it does not depend on hash seeds.
"""
import collections, json, os, statistics, sys

D = os.path.dirname(os.path.abspath(__file__))
GROUPS = [("rewrite_B", "rewriting, Tier B"), ("rewrite_A", "rewriting, Tier A"), ("control", "control")]
OUTCOMES = [("proved", "proved"), ("no_proof_le_Nmax", "no proof ≤ N"), ("crash", "memory crash"),
            ("memout", "memout (solver)"), ("timeout", "timeout")]
RULE_BINS = [(0, 5, "0–5"), (6, 10, "6–10"), (11, 15, "11–15"), (16, 10**9, "16 or more")]


def load(p):
    return [json.loads(l) for l in open(p) if l.strip()] if os.path.exists(p) else []


def fmt(x):
    if isinstance(x, float):
        return f"{int(x):,}" if x.is_integer() else f"{x:,.1f}"
    return f"{x:,}" if isinstance(x, int) else str(x)


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "| " + " | ".join("---" for _ in head) + " |"]
    out += ["| " + " | ".join(fmt(x) for x in r) + " |" for r in rows]
    return out


def pct(a, b):
    return f"{100 * a / b:.1f}%" if b else "–"


def med(xs):
    return statistics.median(xs) if xs else None


def gd(fam, tot):
    return (fam.get("8 groundness", 0) + fam.get("5 decomposition", 0)) / tot if tot else 0.0


def main(rundir):
    goals = {g["key"]: g for g in load(os.path.join(D, "goals.jsonl"))}
    specs = {s["key"]: s for s in load(os.path.join(D, "specs.jsonl"))}
    rules = {r["key"]: r for r in load(os.path.join(D, "rules.jsonl"))}
    final = {r["key"]: r for r in load(os.path.join(D, "inputs", "final.jsonl"))}
    pop = {p["key"]: p for p in load(os.path.join(D, "inputs", "population.jsonl"))}
    k0 = {r["key"]: r for r in load(os.path.join(D, "inputs", "scaling_k0.jsonl"))}
    res = {r["key"]: r for r in load(os.path.join(rundir, "results.jsonl"))}
    siz = {r["key"]: r for r in load(os.path.join(rundir, "sizes.jsonl"))}
    hp = os.path.join(rundir, "header.json")
    hdr = json.load(open(hp)) if os.path.exists(hp) else {}
    keys = sorted(k for k in specs if k in res)
    grp = {k: specs[k]["probe_group"] for k in keys}
    g7 = lambda k: goals[k[4:]]

    def lastn(r):
        return r.get("N") if r["outcome"] != "crash" else r.get("last_N")

    def size(k, n):
        return siz.get(f"{k}@N{n}", {})

    def m7_at(k, n):
        """milestone 7's clauses for the same goal at N = n, from its per-N record (none if it crashed)"""
        for x in final[k[4:]].get("per_N") or []:
            if x["N"] == n:
                return x["clauses"]
        return None

    def propext_goal(k):
        return "propext" in pop.get(k[4:], {}).get("obstacles", [])

    out = ["# 8a: the rewriting probe (M8_PLAN §2, amendment 4.1)", "",
           "Generated by `eval/m8a/report.py` from the data files alone. Facts only; reading them is for 8b.", ""]
    m = hdr.get("machine", {})
    out += [f"Run `{os.path.relpath(rundir, os.path.dirname(D))}`: {len(keys)} of {len(specs)} specs, commit "
            f"`{str(hdr.get('git_commit', '?'))[:7]}`, memory cap {fmt(hdr.get('cap_mb', 2500))} MB, watchdog "
            f"{hdr.get('watchdog_s', 300)} s, shards of {hdr.get('shard_size', '?')}; {m.get('cpu', '?')}, "
            f"{fmt(m.get('ram_mib', 0))} MiB. The shard's limits are milestone 7's: solver 20 s per call, N loop 120 s, "
            "N ≤ 10 for the rewriting goals and N ≤ the original N for the controls, all refinements on. `countOnly` "
            "sizes are counted at N = 5, at each run's last N, and for a control also at its original N.", ""]
    stops = [k for k in keys if "stop" in res[k]]
    out += [f"**Stop rules (§2.5).** Runs with a `stop` field: {len(stops)}"
            + ("".join(f"; `{k}`: {res[k]['stop']}" for k in stops)) + ".", ""]

    # 1. outcomes per group
    rows = []
    for g, name in GROUPS:
        ks = [k for k in keys if grp[k] == g]
        c = collections.Counter(res[k]["outcome"] for k in ks)
        rows.append([name, len(ks)] + [c.get(o, 0) for o, _ in OUTCOMES]
                    + [sum(v for o, v in c.items() if o not in dict(OUTCOMES))])
    out += ["## Outcomes per group", ""] + table(["group", "runs"] + [n for _, n in OUTCOMES] + ["other"], rows) + [""]

    # 2. proved at N
    rows = []
    for g, name in GROUPS:
        c = collections.Counter(res[k]["N"] for k in keys if grp[k] == g and res[k]["outcome"] == "proved")
        rows.append([name, sum(c.values())] + [c.get(n, 0) for n in range(1, 11)])
    out += ["## Proved at N", ""] + table(["group", "proved"] + [f"N = {n}" for n in range(1, 11)], rows) + [""]

    # 3. proved share by number of rules (rules accepted by the compiler)
    def acc_rules(k):
        r = rules[k]
        return r["probe_rules"] - sum(1 for c, _ in r["H_rejected"] if c.startswith("_probe."))
    rows = []
    for g, name in GROUPS:
        for lo, hi, b in RULE_BINS:
            ks = [k for k in keys if grp[k] == g and lo <= acc_rules(k) <= hi]
            if ks:
                p = sum(1 for k in ks if res[k]["outcome"] == "proved")
                rows.append([name, b, len(ks), p, pct(p, len(ks))])
    out += ["## Proved share by number of rules", "",
            "Rules the compiler accepts (generated rules and `propext` equations, `eval/m8a/rules.jsonl`).", ""]
    out += table(["group", "accepted rules", "runs", "proved", "share"], rows) + [""]

    # 4. CNF sizes and family shares against milestone 7, at N = 5
    rows = []
    for g, name in GROUPS:
        ks = [k for k in keys if grp[k] == g]
        pairs = [(size(k, 5)["clauses"], m7_at(k, 5)) for k in ks if size(k, 5).get("clauses")]
        both = [(a, b) for a, b in pairs if b]
        sh = [gd(size(k, 5)["families"], size(k, 5)["clauses"]) for k in ks if size(k, 5).get("clauses")]
        rows.append([name, len(pairs), fmt(int(med([a for a, _ in pairs]))) if pairs else "–", len(both),
                     fmt(int(med([b for _, b in both]))) if both else "–",
                     f"{med([a / b for a, b in both]):.1f}" if both else "–", f"{100 * med(sh):.1f}" if sh else "–"])
    out += ["## CNF size at N = 5, against milestone 7", "",
            "Clauses at N = 5 (`countOnly`, with the rules) for every run, and milestone 7's clauses for the same goal at "
            "N = 5 where its per-N record has them (not for goals that crashed before N = 5 in milestone 7). The ratio "
            "is the median over goals with both. *g + d*: the median share of groundness plus decomposition.", ""]
    out += table(["group", "runs counted", "median clauses, 8a", "with a milestone 7 count", "median clauses, milestone 7",
                  "median ratio", "g + d %"], rows) + [""]
    fams = sorted({f for k in keys for f in size(k, 5).get("families", {})}, key=lambda f: int(f.split()[0]))
    rows = []
    for g, name in GROUPS:
        ks = [k for k in keys if grp[k] == g and size(k, 5).get("clauses")]
        if ks:
            rows.append([name, len(ks)] + [f"{100 * statistics.mean(size(k, 5)['families'].get(f, 0) / size(k, 5)['clauses'] for k in ks):.1f}"
                                           for f in fams])
    out += ["Family shares at N = 5 (mean of per-run shares, %):", ""]
    out += table(["group", "runs"] + [f.split(" ", 1)[1].split(" (")[0] for f in fams], rows) + [""]

    # 5. rewriting goals proved
    rows = []
    for k in keys:
        r = res[k]
        if grp[k] != "control" and r["outcome"] == "proved":
            used = sorted(r.get("probe_extra_used") or [])
            rows.append([f"`{g7(k)['id']}`", r["N"], "yes" if r.get("uses_propext") else "no",
                         ", ".join(f"`{u}`" for u in used) or "–", f"`{r.get('skeleton')}`"])
    out += ["## Rewriting goals proved", "",
            "Each proof's N, whether it uses a `propext` equation, the constants outside H_main it uses (generated rules, "
            "`propext` equations, `Eq.refl`/`Eq.symm`/`Eq.trans`), and its skeleton. Milestone 7 did not prove any of "
            "these goals (no proof ≤ 10, or a memory crash).", ""]
    out += (table(["goal", "N", "propext equation", "used outside H_main", "skeleton"], rows) if rows else ["None."]) + [""]

    # 6. propext goals separately
    rows = []
    for g, name in GROUPS[:2]:
        for lab, f in (("`propext` among the obstacles", True), ("no `propext` obstacle", False)):
            ks = [k for k in keys if grp[k] == g and propext_goal(k) == f]
            c = collections.Counter(res[k]["outcome"] for k in ks)
            only = sum(1 for k in ks if pop[k[4:]]["obstacles"] == ["propext"])
            withp = sum(1 for k in ks if (rules[k].get("probe_propext") or 0) > 0)
            up = sum(1 for k in ks if res[k]["outcome"] == "proved" and res[k].get("uses_propext"))
            rows.append([name, lab, len(ks), only if f else "–", withp, c.get("proved", 0), up,
                         c.get("no_proof_le_Nmax", 0), c.get("crash", 0) + c.get("memout", 0), c.get("timeout", 0)])
    out += ["## Goals with `propext` among their obstacles (amendment 4.1 decision 6)", "",
            "*only propext*: `propext` is the goal's only obstacle. *with an equation*: the goal has at least one "
            "`propext` equation among its rules.", ""]
    out += table(["group", "goals", "runs", "only propext", "with an equation", "proved", "proved using an equation",
                  "no proof ≤ 10", "memory crash", "timeout"], rows) + [""]

    # 7. crashed runs: last N and clauses there, against milestone 7
    rows = []
    for k in keys:
        r = res[k]
        if r["outcome"] in ("crash", "memout"):
            n = lastn(r)
            z = size(k, n)
            b = m7_at(k, n)
            a = z.get("clauses")
            rows.append([grp[k], f"`{g7(k)['id']}`", n, a if a else z.get("status", "–"),
                         final[k[4:]]["outcome"], b if b else "–", f"{a / b:.1f}" if (a and b) else "–",
                         f"{100 * gd(z['families'], a):.0f}" if a else "–"])
    out += ["## Crashed runs", "",
            "The last N reached (the N whose CNF was being built or solved when the cap was hit), the clauses there "
            "(`countOnly`, with the rules), and milestone 7's outcome and clauses for the same goal at the same N.", ""]
    out += table(["group", "goal", "last N", "clauses, 8a", "milestone 7 outcome", "clauses, milestone 7", "ratio",
                  "g + d %"], rows) + [""]
    rr = [x for x in rows if x[6] != "–"]
    if rr:
        v = sorted(float(x[6]) for x in rr)
        out += [f"Ratio over the {len(rr)} crashed runs with a milestone 7 count at the same N: median {med(v):.1f}, "
                f"range {v[0]:.1f}–{v[-1]:.1f}. Smallest crashed CNF: "
                f"{fmt(min(x[3] for x in rows if isinstance(x[3], int)))} clauses.", ""]

    # 8. controls' cost
    rows = []
    for k in keys:
        if grp[k] != "control":
            continue
        g = g7(k)
        n0 = g["orig_N"]
        a = size(k, n0).get("clauses")
        b = k0[g["key"]]["sizes"]["clauses"]
        r = res[k]
        feas = r["outcome"] == "proved" and r["N"] <= n0
        rows.append([f"`{g['id']}`", n0, r["outcome"], r.get("N") if r["outcome"] == "proved" else f"(last {lastn(r)})",
                     a if a else size(k, n0).get("status", "–"), b, f"{a / b:.1f}" if a else "–", "yes" if feas else "no",
                     "yes" if r.get("uses_rule") else "no"])
    rows.sort(key=lambda x: (x[1], x[0]))
    out += ["## Controls: the cost of the rules", "",
            "Clauses at the original N with the rules (`countOnly`) against milestone 7's k = 0 count "
            "(`eval/scaling_full/sizes.jsonl` on `m7-data`). *Feasible*: proved at or below the original N within the limits.", ""]
    out += table(["goal", "original N", "outcome", "N", "clauses, 8a", "clauses, milestone 7", "ratio", "feasible",
                  "uses a rule"], rows) + [""]
    fe = sum(1 for x in rows if x[7] == "yes")
    rat = sorted(float(x[6]) for x in rows if x[6] != "–")
    by = collections.defaultdict(list)
    for x in rows:
        by["1" if x[1] == 1 else "2" if x[1] == 2 else "3–4" if x[1] <= 4 else "5 or more"].append(x)
    out += [f"Feasible: {fe} of {len(rows)}. Ratio at the original N: median {med(rat):.1f}, range {rat[0]:.1f}–{rat[-1]:.1f}."
            if rat else f"Feasible: {fe} of {len(rows)}.", ""]
    out += table(["original N", "controls", "feasible", "median ratio"],
                 [[b, len(xs), sum(1 for x in xs if x[7] == "yes"),
                   f"{med([float(x[6]) for x in xs if x[6] != '–']):.1f}" if any(x[6] != "–" for x in xs) else "–"]
                  for b, xs in sorted(by.items(), key=lambda z: ["1", "2", "3–4", "5 or more"].index(z[0]))]) + [""]

    # 9. rules
    kinds = collections.Counter(n.split(".")[-2] for k in keys for n in rules[k]["probe_rule_names"])
    rej = collections.Counter(c.split(".")[-2] for k in keys for c, _ in rules[k]["H_rejected"] if c.startswith("_probe."))
    rows = []
    for g, name in GROUPS:
        ks = [k for k in keys if grp[k] == g]
        n = sorted(rules[k]["probe_rules"] for k in ks)
        a = sorted(acc_rules(k) for k in ks)
        q = lambda xs: xs[min(len(xs) - 1, int(0.9 * len(xs)))]
        rows.append([name, len(ks), f"{fmt(med(n))} / {q(n)} / {n[-1]}", f"{fmt(med(a))} / {q(a)} / {a[-1]}",
                     sum(1 for k in ks if (rules[k].get("probe_propext") or 0) > 0)])
    out += ["## The rules", "",
            "Built by kind: " + ", ".join(f"`{x}` {fmt(v)}" for x, v in sorted(kinds.items())) + "; rejected by the compiler: "
            + ", ".join(f"`{x}` {fmt(v)}" for x, v in sorted(rej.items())) + f"; failed to build: "
            f"{sum(len(rules[k]['probe_failed']) for k in keys)}; positions skipped because the result type depends on "
            f"them: {sum(rules[k].get('probe_skipped_dep', 0) for k in keys)}.", ""]
    out += table(["group", "goals", "rules: median / p90 / max", "accepted: median / p90 / max", "goals with a propext equation"],
                 rows) + [""]
    name = "PROBE.md" if os.path.basename(os.path.normpath(rundir)) == "full" else f"PROBE_{os.path.basename(os.path.normpath(rundir))}.md"
    open(os.path.join(D, name), "w").write("\n".join(out) + "\n")
    print(f"wrote eval/m8a/{name}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(D, "full"))
