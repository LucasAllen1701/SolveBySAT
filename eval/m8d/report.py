#!/usr/bin/env python3
"""8d (M8_PLAN.md 4.6): write eval/m8d/EVAL8.md from the data files alone.

  python3 eval/m8d/report.py

Reads eval/m8d/inputs/ (milestone 7's eval/final/results.jsonl and eval/specs_full.jsonl, from tag
m7-data), eval/m8d/sample.tsv, eval/m8d/specs.jsonl, eval/m8d/runs/ (results.jsonl, sizes.jsonl,
timing.json, driver.jsonl) and eval/m8d/timing_pilot.json. States facts; recommends nothing.
"""
import hashlib, json, math, os, statistics

D = os.path.dirname(os.path.abspath(__file__))
RUNS = os.path.join(D, "runs")
GROUPS = ["crash_B", "crash_A", "control_proved", "control_no_proof"]
CRASH_GROUPS = GROUPS[:2]
CONTROLS = GROUPS[2:]
POP = {"crash_B": 490, "crash_A": 807, "control_proved": 976, "control_no_proof": 3083}
CAT = ["proved", "no proof ≤ 10", "timed out", "still crashed", "other"]
FAMILIES = ["1 node assignment", "2 tree shape", "3 context (local hypotheses, ancestors)", "4 matching",
            "5 decomposition", "6 links (environment copies)", "7 eigenvariables, occurs check, scope",
            "8 groundness", "10 symmetry breaking", "11 node bounds"]


def load(p):
    return [json.loads(l) for l in open(p) if l.strip()] if os.path.exists(p) else []


def md5(p):
    return hashlib.md5(open(p, "rb").read()).hexdigest()


def fmt(x):
    return f"{x:,}"


def pct(a, b):
    return f"{100 * a / b:.1f}%" if b else "–"


def wilson(k, n, z=1.959963984540054):
    if n == 0:
        return (float("nan"), float("nan"))
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0.0, c - h), min(1.0, c + h))


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "| " + " | ".join("---" for _ in head) + " |"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return out


def category(r):
    o = r["outcome"]
    if o == "proved":
        return "proved"
    if o == "no_proof_le_Nmax":
        return "no proof ≤ 10"
    if o == "timeout" or (o == "crash" and r.get("cause") == "watchdog"):
        return "timed out"
    if o == "crash" and r.get("cause") == "oom":
        return "still crashed"
    return "other"


def outcome_label(r):
    o = r["outcome"]
    if o == "crash":
        return f"crash ({r.get('cause')})"
    if o == "timeout":
        return f"timeout ({r.get('timeout_kind', '?')})"
    return o


def last_n(r):
    return r.get("last_N") if r["outcome"] == "crash" else r.get("N")


def reference_of(r):
    """As Test/eval_driver.py's reference_of and Test/EvalRun.lean's referenceOf."""
    rows = r.get("per_N") or []
    unsat = set()
    if r.get("outcome") == "crash" or (r.get("outcome") == "timeout" and not rows):
        unsat |= set(range(1, r.get("last_N") or 1))
    unsat |= {x["N"] for x in rows if x.get("result") == "unsat"}
    return unsat, (r.get("N") if r.get("outcome") == "proved" else None)


def exactness(ref, r):
    """The stop rules of 4.6, recomputed from the records (the shard's and the driver's checks)."""
    unsat, proved = ref
    if r["outcome"] == "proved":
        if r["N"] in unsat:
            return "proof where milestone 7 was UNSAT"
        if proved is not None and proved != r["N"]:
            return "proof at another N"
    for x in r.get("per_N") or []:
        if x["result"] in ("unsat", "early_exit") and proved == x["N"]:
            return "UNSAT or early exit at milestone 7's proof N"
    if r["outcome"] == "crash" and proved is not None and r.get("last_N") and proved < r["last_N"]:
        return "crash past milestone 7's proof N"
    return None


def main():
    m7 = {r["key"]: r for r in load(os.path.join(D, "inputs", "results.jsonl"))}
    sample = [l.rstrip("\n").split("\t") for l in open(os.path.join(D, "sample.tsv")) if l.strip()]
    grp = {k: g for g, k in sample}
    res = {r["key"]: r for r in load(os.path.join(RUNS, "results.jsonl"))}
    siz = {z["key"]: z for z in load(os.path.join(RUNS, "sizes.jsonl"))}
    tm = json.load(open(os.path.join(RUNS, "timing.json")))
    tp = json.load(open(os.path.join(D, "timing_pilot.json")))
    keys = {g: [k for gg, k in sample if gg == g] for g in GROUPS}
    L = ["# 8d: evaluation of the tactic as users run it (M8_PLAN 4.6)", "",
         "Generated by `python3 eval/m8d/report.py` from the data files in `eval/m8d/`. Settings: R1 and R2 on "
         "(the tactic's defaults), milestone 7's H, no rewriting rules, baselines off, the N loop from 1 to 10 with "
         "milestone 7's limits (2.5 GB cap, the N-loop limits, the 300 s watchdog).", ""]

    # inputs
    L += ["## Inputs and sample", ""]
    L += table(["file", "md5"], [
        ["`inputs/results.jsonl` (milestone 7's `eval/final/results.jsonl`)", f"`{md5(os.path.join(D, 'inputs', 'results.jsonl'))}`"],
        ["`inputs/specs_full.jsonl` (milestone 7's `eval/specs_full.jsonl`)", f"`{md5(os.path.join(D, 'inputs', 'specs_full.jsonl'))}`"],
        ["`sample.tsv`", f"`{md5(os.path.join(D, 'sample.tsv'))}`"],
        ["`specs.jsonl`", f"`{md5(os.path.join(D, 'specs.jsonl'))}`"]])
    L.append("")
    main_ = [r for r in m7.values() if r["key"].startswith("main:")]
    rows = []
    for g in GROUPS:
        tier = {"crash_B": "B", "crash_A": "A"}.get(g)
        o = {"crash_B": "crash", "crash_A": "crash", "control_proved": "proved", "control_no_proof": "no_proof_le_Nmax"}[g]
        pop = [r for r in main_ if r["outcome"] == o and (tier is None or r["key"][5] == tier)]
        oom = sum(1 for r in pop if r.get("cause") == "oom")
        rows.append([g, fmt(len(pop)), fmt(POP[g]), len(keys[g]), sum(1 for k in keys[g] if k in res),
                     f"{oom} of {len(pop)}" if o == "crash" else "–"])
    L += table(["group", "population (recomputed)", "population (4.6)", "sample", "runs done", "milestone 7 cause `oom`"], rows)
    L.append("")

    # stops
    stops = [(k, r["stop"]) for k, r in res.items() if "stop" in r]
    re_ex = [(k, exactness(reference_of(m7[k]), r)) for k, r in res.items()]
    re_ex = [(k, m) for k, m in re_ex if m]
    L += ["## Stop rules (4.6)", "",
          f"- Stops recorded by the harness: {len(stops)}." + "".join(f" `{k}`: {m}." for k, m in stops),
          f"- The exactness rules recomputed here from the records against milestone 7's: {len(re_ex)} disagreements."
          + "".join(f" `{k}`: {m}." for k, m in re_ex), ""]

    # outcomes
    L += ["## Outcomes per group", ""]
    rows = []
    for g in GROUPS:
        c = {x: sum(1 for k in keys[g] if k in res and category(res[k]) == x) for x in CAT}
        rows.append([g, sum(1 for k in keys[g] if k in res)] + [c[x] for x in CAT])
    L += table(["group", "runs"] + CAT, rows)
    L += ["", "Timed out: the N-loop limit (outcome `timeout`) or the 300 s watchdog (a crash with cause "
          "`watchdog`). Still crashed: a crash with cause `oom` (the 2.5 GB cap).", ""]
    L += ["### Transitions from milestone 7's outcomes", ""]
    trans = {}
    for g in GROUPS:
        for k in keys[g]:
            if k in res:
                t = (g, outcome_label(m7[k]), outcome_label(res[k]))
                trans[t] = trans.get(t, 0) + 1
    L += table(["group", "milestone 7", "8d", "runs"], [[g, a, b, n] for (g, a, b), n in sorted(trans.items(), key=lambda x: (GROUPS.index(x[0][0]), x[0][1], -x[1], x[0][2]))])
    L.append("")

    # crash groups
    L += ["## The crash groups", "",
          "Shares of the sample with Wilson 95% intervals, and those shares applied to the group's population.", ""]
    for g in CRASH_GROUPS:
        ks = [k for k in keys[g] if k in res]
        n = len(ks)
        rows = []
        for x in CAT[:4]:
            c = sum(1 for k in ks if category(res[k]) == x)
            lo, hi = wilson(c, n)
            rows.append([x, c, f"{100 * c / n:.1f}%" if n else "–", f"[{100 * lo:.1f}%, {100 * hi:.1f}%]",
                         f"{POP[g] * c / n:.0f}" if n else "–", f"[{POP[g] * lo:.0f}, {POP[g] * hi:.0f}]"])
        other = sum(1 for k in ks if category(res[k]) == "other")
        L += [f"### {g} ({n} runs, population {POP[g]})", ""]
        L += table(["outcome", "runs", "share", "Wilson 95%", "population estimate", "interval"], rows)
        L += ["", f"Other outcomes: {other}.", ""]
        # how far the still-crashed and timed-out runs got, against milestone 7
        rows = []
        for x in ("still crashed", "timed out", "no proof ≤ 10", "proved"):
            kk = [k for k in ks if category(res[k]) == x]
            if not kk:
                continue
            d = [(last_n(res[k]) or 0) - (m7[k].get("last_N") or 0) for k in kk]
            rows.append([x, len(kk), f"{statistics.median([last_n(res[k]) or 0 for k in kk]):g}",
                         f"{statistics.median([m7[k].get('last_N') or 0 for k in kk]):g}",
                         sum(1 for v in d if v > 0), sum(1 for v in d if v == 0), sum(1 for v in d if v < 0)])
        L += table(["8d outcome", "runs", "median last N, 8d", "median last N reached, milestone 7",
                    "8d further", "same N", "8d less far"], rows)
        L.append("")

    # proved at N and early exits
    L += ["## Proofs and early exits", "", "### Proved at N", ""]
    rows = []
    for g in GROUPS:
        ns = [res[k]["N"] for k in keys[g] if k in res and res[k]["outcome"] == "proved"]
        rows.append([g, len(ns)] + [sum(1 for n in ns if n == i) for i in range(1, 11)])
    L += table(["group", "proved"] + [f"N = {i}" for i in range(1, 11)], rows)
    L.append("")
    newp = [(g, k, res[k]) for g in CRASH_GROUPS for k in keys[g] if k in res and res[k]["outcome"] == "proved"]
    if newp:
        L += ["New proofs in the crash groups:", ""]
        L += [f"- `{k}` ({g}), N = {r['N']}: `{r.get('skeleton')}`" for g, k, r in newp]
        L.append("")
    L += ["### Early exits (R1: s(root) > N, nothing is solved)", ""]
    rows = []
    for g in GROUPS:
        ks = [k for k in keys[g] if k in res]
        ee = [k for k in ks if any(x["result"] == "early_exit" for x in res[k].get("per_N") or [])]
        allN = [k for k in ee if res[k]["outcome"] == "no_proof_le_Nmax" and all(x["result"] == "early_exit" for x in res[k]["per_N"])]
        nee = sum(sum(1 for x in res[k]["per_N"] if x["result"] == "early_exit") for k in ee)
        nrow = sum(len(res[k].get("per_N") or []) for k in ks)
        rows.append([g, len(ks), len(ee), allN and len(allN) or 0, f"{nee} of {nrow}"])
    L += table(["group", "runs", "runs with an early exit", "runs with an early exit at every N (no proof at any N)",
                "N with an early exit"], rows)
    L.append("")

    # controls
    L += ["## The controls", "", "### Agreement with milestone 7", ""]
    rows = []
    for g in CONTROLS:
        ks = [k for k in keys[g] if k in res]
        same = sum(1 for k in ks if res[k]["outcome"] == m7[k]["outcome"] and res[k].get("N") == m7[k].get("N"))
        lim = [k for k in ks if category(res[k]) in ("timed out", "still crashed")]
        agree_n = 0
        dis_n = 0
        for k in ks:
            a = {x["N"]: x["result"] for x in res[k].get("per_N") or []}
            b = {x["N"]: x["result"] for x in m7[k].get("per_N") or []}
            for n in sorted(set(a) & set(b)):
                ra = "unsat" if a[n] in ("unsat", "early_exit") else a[n]
                if ra in ("unsat", "proved") and b[n] in ("unsat", "proved"):
                    if ra == b[n]:
                        agree_n += 1
                    else:
                        dis_n += 1
        rows.append([g, len(ks), same, len(lim), agree_n, dis_n])
    L += table(["group", "runs", "same outcome and N", "at a resource limit", "N answered by both, same answer",
                "N answered by both, different answer"], rows)
    L += ["", "An early exit counts as UNSAT at its N. Resource limits among the controls:" +
          ("".join(f" `{k}` ({outcome_label(res[k])}, milestone 7 {outcome_label(m7[k])} at N = {m7[k].get('N')})."
                   for g in CONTROLS for k in keys[g] if k in res and category(res[k]) in ("timed out", "still crashed", "other"))
           or " none."), ""]
    L += ["### Times where both answered the same N", "",
          "Per N answered by both runs (UNSAT, the early exit as UNSAT, or proved): the sum of the solver time "
          "(`solve_s`, whole seconds in milestone 7) and of the encoding time (`encode_ms`), pooled; the per-goal "
          "ratio of the N loops' sums as median [min, max] over goals with a non-zero milestone 7 sum.", ""]
    rows = []
    for g in CONTROLS:
        s8 = s7 = e8 = e7 = 0.0
        nn = 0
        rs, re = [], []
        for k in keys[g]:
            if k not in res:
                continue
            a = {x["N"]: x for x in res[k].get("per_N") or []}
            b = {x["N"]: x for x in m7[k].get("per_N") or []}
            gs8 = gs7 = ge8 = ge7 = 0.0
            for n in sorted(set(a) & set(b)):
                ra = "unsat" if a[n]["result"] == "early_exit" else a[n]["result"]
                if ra == b[n]["result"] and ra in ("unsat", "proved"):
                    nn += 1
                    gs8 += a[n].get("solve_s") or 0
                    gs7 += b[n].get("solve_s") or 0
                    ge8 += a[n].get("encode_ms") or 0
                    ge7 += b[n].get("encode_ms") or 0
            s8 += gs8; s7 += gs7; e8 += ge8; e7 += ge7
            if gs7 > 0:
                rs.append(gs8 / gs7)
            if ge7 > 0:
                re.append(ge8 / ge7)
        mm = lambda v: f"{statistics.median(v):.2f} [{min(v):.2f}, {max(v):.2f}]" if v else "–"
        rows.append([g, nn, f"{s8:.1f}", f"{s7:.1f}", f"{s8 / s7:.2f}" if s7 else "–", mm(rs),
                     f"{e8 / 1000:.1f}", f"{e7 / 1000:.1f}", f"{e8 / e7:.2f}" if e7 else "–", mm(re)])
    L += table(["group", "N", "solve s, 8d", "solve s, milestone 7", "ratio", "per goal", "encode s, 8d",
                "encode s, milestone 7", "ratio", "per goal"], rows)
    L.append("")
    rows = []
    for g in CONTROLS:
        kk = [k for k in keys[g] if k in res and m7[k].get("loop_ms") and res[k].get("loop_ms") is not None]
        a = sum(res[k]["loop_ms"] for k in kk) / 1000
        b = sum(m7[k]["loop_ms"] for k in kk) / 1000
        rows.append([g, len(kk), f"{a:.1f}", f"{b:.1f}", f"{a / b:.2f}" if b else "–"])
    L += ["The whole N loop (`loop_ms`, encoding, solving and decoding), for controls with both records:", ""]
    L += table(["group", "runs", "8d s", "milestone 7 s", "ratio"], rows)
    L.append("")

    # sizes
    L += ["## Sizes (`countOnly`, R1 and R2 on)", "",
          "Each at N = 5 and at the run's last N (for a crash, the N it reached), each in its own capped process. "
          "A count that the cap stopped is `memout`.", ""]
    for which in ("N = 5", "last N"):
        rows = []
        fam = {g: {f: 0 for f in FAMILIES} for g in GROUPS}
        tot = {g: [0, 0] for g in GROUPS}
        for g in GROUPS:
            st = {}
            for k in keys[g]:
                if k not in res:
                    continue
                n = 5 if which == "N = 5" else (last_n(res[k]) or 1)
                z = siz.get(f"{k}@N{n}")
                s = "missing" if z is None else ("early exit" if z.get("early_exit") else z.get("status", "?"))
                st[s] = st.get(s, 0) + 1
                if z and z.get("status") == "ok":
                    tot[g][0] += z["clauses"]; tot[g][1] += z["vars"]
                    for f, v in (z.get("families") or {}).items():
                        fam[g][f] = fam[g].get(f, 0) + v
            rows.append([g, ", ".join(f"{s} {c}" for s, c in sorted(st.items())), fmt(tot[g][0]), fmt(tot[g][1])])
        L += [f"### At {which}", ""]
        L += table(["group", "records", "clauses (pooled, counted records)", "variables"], rows)
        L.append("")
        L += table(["family"] + GROUPS, [[f] + [f"{fmt(fam[g].get(f, 0))} ({pct(fam[g].get(f, 0), tot[g][0])})" for g in GROUPS] for f in FAMILIES])
        L.append("")
    # N = 5 clauses against milestone 7's per-N record at N = 5
    rows = []
    for g in GROUPS:
        a = b = 0
        n = 0
        rr = []
        for k in keys[g]:
            z = siz.get(f"{k}@N5")
            m = {x["N"]: x for x in m7[k].get("per_N") or []}.get(5)
            if z and z.get("status") == "ok" and m and m.get("clauses"):
                n += 1; a += z["clauses"]; b += m["clauses"]; rr.append(z["clauses"] / m["clauses"])
        rows.append([g, n, fmt(a), fmt(b), f"{a / b:.3f}" if b else "–",
                     f"{statistics.median(rr):.3f} [{min(rr):.3f}, {max(rr):.3f}]" if rr else "–"])
    L += ["### Clauses at N = 5 against milestone 7's", "",
          "Where milestone 7 has a per-N record at N = 5 (none for its crashes):", ""]
    L += table(["group", "goals", "8d", "milestone 7", "pooled ratio", "per goal, median [min, max]"], rows)
    L.append("")

    # time
    drv = load(os.path.join(RUNS, "driver.jsonl"))
    L += ["## Time", "",
          f"- Runs: {tm['runs_s'] / 3600:.2f} h; sizes: {tm['sizes_s'] / 3600:.2f} h (the pilot included: runs "
          f"{tp['runs_s'] / 60:.1f} min, sizes {tp['sizes_s'] / 60:.1f} min).",
          f"- Driver passes: {len(drv)}; results at the end of the last: {drv[-1].get('results_at_end') if drv else '–'}.", ""]
    rows = []
    for g in GROUPS:
        ks = [k for k in keys[g] if k in res]
        t = [(res[k]["total_ms"] / 1000) if res[k].get("total_ms") is not None else (res[k].get("elapsed_s") or 0) for k in ks]
        rows.append([g, len(ks), f"{sum(t) / 60:.1f}", f"{statistics.median(t):.1f}" if t else "–", f"{max(t):.1f}" if t else "–"])
    L += table(["group", "runs", "total min", "median s per run", "max s"], rows)
    L.append("")
    open(os.path.join(D, "EVAL8.md"), "w").write("\n".join(L).rstrip("\n") + "\n")


if __name__ == "__main__":
    main()
